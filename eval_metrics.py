"""Measurement harness for CoverUp experiments on the two MuTAP datasets.

Metrics requested:
  RQ1 (main performance): Coverage, Pass Rate, Mutation Score
  RQ2 (backbone)        : Coverage, Pass Rate, Wall time and Cost

The harness is method-agnostic: it measures ANY test suite against ANY
Program-Under-Test (PUT), so it works for suites generated by CoverUp and for
the baselines shipped with the datasets (MuTAP/Codex, Copilot, Pynguin).

Two suite styles occur in these datasets and are handled transparently:
  * inline - MuTAP/Codex/Copilot files that embed the PUT source, define
             ``def test():`` and never call it (MuTAP runs that test part
             against each mutant);
  * import - CoverUp/Pynguin/pytest files that import the module under test.

Metric definitions, applied identically to every method:
  Coverage       Share of the PUT's executable lines executed by the suite,
                 measured with SlipCover (the instrumenter CoverUp uses),
                 restricted to the PUT file.
  Pass Rate      Passing test units / total test units.  Every test function
                 runs in isolation so one broken test cannot mask the others.
  Mutation Score MuTAP's protocol: killed / (all - problematic).  A mutant is
                 killed when the suite fails on an assertion, survives when it
                 runs clean, and is "problematic" (excluded from the
                 denominator) on timeout or any non-assertion error.
  Wall time      Generation time of the suite (CoverUp run).  For pre-existing
                 baseline suites it is intentionally left empty rather than
                 conflated with evaluation time.
  Cost           USD as accounted by CoverUp itself (litellm completion_cost,
                 persisted in CoverUp's checkpoint file).
"""

from __future__ import annotations

import ast
import json
import os
import re
import shutil
import subprocess
import sys
import sysconfig
import site
import tempfile
import typing as T
import time
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent
VENV = ROOT / ".venv"


def BIN(name: str) -> str:
    """Return a runnable project executable on both POSIX and Windows.

    The repository may contain a stale Linux ``.venv/bin`` copied from another
    machine.  On Windows those text launcher files are not executable, so
    prefer the active interpreter/user scripts or PATH instead.
    """
    if name == "python":
        return sys.executable

    candidates = []
    if os.name == "nt":
        script_dirs = [
            VENV / "Scripts",
            Path(sysconfig.get_path("scripts")),
        ]
        for base in (site.getusersitepackages(), site.getuserbase()):
            if base:
                script_dirs.extend([
                    Path(base).parent / "Scripts",
                    Path(base) / "Scripts",
                ])
        for script_dir in script_dirs:
            candidates.extend([
                script_dir / (name + ".exe"),
                script_dir / name,
            ])
        for candidate in candidates:
            if candidate.exists() and candidate.suffix == ".exe":
                return str(candidate)
    else:
        candidate = VENV / "bin" / name
        if candidate.exists():
            return str(candidate)
    return shutil.which(name) or name


PY = BIN("python")
PYTEST = BIN("pytest")


def _count(pattern: str, text: str) -> int:
    m = re.search(pattern, text)
    return int(m.group(1)) if m else 0


def _resolve_cmd(cmd) -> T.List[str]:
    """Resolve module-based or filesystem commands to a runnable command."""
    parts = [str(c) for c in cmd]
    if len(parts) >= 2 and parts[0] == PY and parts[1] == "-m":
        return parts
    executable = parts[0]
    if not Path(executable).exists():
        executable = BIN(executable)
    resolved = [executable] + parts[1:]
    if (len(resolved) >= 2 and resolved[0] == PY and resolved[1] == PYTEST
            and Path(PYTEST).suffix == ".exe"):
        # PYTEST is a Windows executable; invoke it directly.
        resolved = [PYTEST] + resolved[2:]
    return resolved


def _run(cmd, cwd: Path, env: dict, timeout: float):
    return subprocess.run(_resolve_cmd(cmd), cwd=str(cwd), env=env,
                          capture_output=True, text=True, timeout=timeout)


def coverup_cmd() -> T.List[str]:
    """Runnable CoverUp CLI, independent from shell PATH."""
    try:
        import coverup  # noqa: F401
        return [PY, "-m", "coverup.coverup"]
    except ImportError:
        return [BIN("coverup")]


