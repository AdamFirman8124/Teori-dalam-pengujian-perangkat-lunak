def _py_files(d: Path) -> T.List[Path]:
    if not d.exists():
        return []
    return sorted(p for p in d.rglob("*.py") if p.stem != "__init__")


def _first_match(globs: T.Sequence[T.Iterable[Path]]) -> T.List[Path]:
    """Files of the first glob that yields anything: suite names vary per task."""
    for g in globs:
        found = sorted(g)
        if found:
            return found
    return []


def humaneval_layout(task: str) -> dict:
    """PUT, provided mutants and shipped baseline suites for one HumanEval task."""
    d = ROOT / "MuTAP" / "HumanEval" / "Testing_HumanEval" / str(task)
    put = d / f"script_{task}.py"
    if not put.exists():
        put = d / f"script_NDS_{task}.py"
    codex = _first_match([
        (d / "Codex").glob("T_O_FS_Mut_all_semticfixed_*.py"),
        (d / "Codex").glob("T_O_FS_Mut_all_*.py"),
        (d / "Codex").glob("T_O_FS_semticfixed_*.py"),
        (d / "Codex").glob("T_O_NDS_Mut_all_semticfixed_*.py"),
        (d / "Codex").glob("T_O_NDS_semticfixed_*.py"),
    ])
    return {
        "dataset": "HumanEval",
        "task": str(task),
        "put": put,
        "mutants": sorted((d / "Mutants").glob("mutant_*.py")),
        "suites": {
            "MuTAP-Codex": codex,
            "Copilot-FS": sorted((d / "Copilot").glob("test_*_cp_few_shot.py")),
            "Pynguin": sorted((d / "Pynguin").glob("test_*.py")),
        },
    }


def refactory_layout(task: str) -> dict:
    """PUT, provided mutants ("wrong" versions) and baselines for Refactory."""
    base = ROOT / "MuTAP" / "Refactory" / "Reference_Scripts"
    q = str(task) if str(task).startswith("q") else f"q{task}"
    d = base / "Tests" / q
    put = d / f"script_{q}.py"
    if not put.exists():
        put = base / "Scripts" / f"{q}.py"
    codex = _first_match([
        (d / "Codex").glob("T_O_FS_Mut_all_semticfixed_{0}.py".format(q)),
        (d / "Codex").glob("T_O_FS_Mut_all_{0}.py".format(q)),
        (d / "Codex").glob("T_O_FS_semticfixed_{0}.py".format(q)),
        (d / "Codex").glob("T_O_FS_{0}.py".format(q)),
    ])
    return {
        "dataset": "Refactory",
        "task": q,
        "put": put,
        "mutants": _py_files(base / "Wrong_st" / q),
        "suites": {
            "MuTAP-Codex": codex,
            "Copilot-FS": sorted(d.glob("script_{0}_cp_few_shot.py".format(q))),
        },
    }


LAYOUTS: T.Dict[str, T.Callable[[str], dict]] = {
    "HumanEval": humaneval_layout,
    "Refactory": refactory_layout,
}


def task_ids(name: str, limit: int | None = None) -> T.List[str]:
    """All task ids of a dataset, in a stable order."""
    if name == "HumanEval":
        base = ROOT / "MuTAP" / "HumanEval" / "Testing_HumanEval"
        ids = sorted((p.name for p in base.iterdir()
                      if p.is_dir() and p.name.isdigit()), key=int)
    else:
        base = ROOT / "MuTAP" / "Refactory" / "Reference_Scripts" / "Scripts"
        ids = [p.stem for p in sorted(base.glob("q*.py"), key=lambda p: int(p.stem[1:]))]
    return ids[:limit] if limit else ids


# --------------------------------------------------------------------------- #
# Suite normalisation
# --------------------------------------------------------------------------- #
TEST_DEF = re.compile(r"^def (test\w*)\(", re.M)


def test_functions(tf: Path) -> T.List[str]:
    """Module-level names that pytest would collect as tests."""
    try:
        tree = ast.parse(tf.read_text())
    except (SyntaxError, OSError, UnicodeDecodeError):
        return []
    return [n.name for n in tree.body
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
            and n.name.startswith("test")]


def _inline_test_part(src: str) -> str:
    """Test part of a MuTAP-style file: everything from the first test def."""
    m = TEST_DEF.search(src)
    return src[m.start():] if m else ""


def prepare_suite(layout: dict, tests: T.Sequence[Path], workdir: Path) -> dict:
    """Materialise `tests` in `workdir` so the PUT is importable, and classify them.

    Returns a dict with:
      style         "inline", "import" or "empty"
      pytest_files  materialised files pytest can collect
      units         [(original file, alias/function name or "")]
      inline_parts  raw test parts (for MuTAP-style mutation testing)
      put           the PUT file, copied into workdir
    """
    put_src = Path(layout["put"])
    put = workdir / put_src.name
    shutil.copy(put_src, put)
    tests = [Path(t) for t in tests if Path(t).exists()]
    if not tests:
        return {"style": "empty", "pytest_files": [], "units": [],
                "inline_parts": [], "put": put}

    sources = {}
    for t in tests:
        sources[t] = t.read_text(errors="ignore")
    inline = [t for t in tests
              if ("import " + put.stem) not in sources[t]
              and ("from " + put.stem + " import") not in sources[t]
              and TEST_DEF.search(sources[t])]
    style = "inline" if inline else "import"

    pytest_files: T.List[Path] = []
    units: T.List[T.Tuple[Path, str]] = []
    inline_parts: T.List[str] = []

    for i, tf in enumerate(tests):
        if style == "inline" and tf in inline:
            part = _inline_test_part(sources[tf])
            fns = TEST_DEF.findall(part)
            if not fns:
                continue
            inline_parts.append(part)
            body = "from {0} import *  # noqa: F401,F403\n\n{1}\n\n".format(put.stem, part)
            for j, fn in enumerate(fns):
                alias = "test_wrapped_{0}".format(j)
                body += "def {0}():\n    {1}()\n\n".format(alias, fn)
                units.append((tf, alias))
            out = workdir / ("test_inline_{0}.py".format(i))
            out.write_text(body)
            pytest_files.append(out)
        else:
            dst = workdir / ("test_imported_{0}.py".format(i))
            shutil.copy(tf, dst)
            pytest_files.append(dst)
            for fn in test_functions(tf):
                units.append((tf, fn))
            if not test_functions(tf) and sources[tf].strip():
                units.append((tf, ""))
    return {"style": style, "pytest_files": pytest_files, "units": units,
            "inline_parts": inline_parts, "put": put}


def _alias_owner(prepared: dict) -> T.Dict[str, Path]:
    """Map aliases created by prepare_suite back to their materialised file."""
    mapping: T.Dict[str, Path] = {}
    for mat in prepared["pytest_files"]:
        for fn in test_functions(mat):
            mapping[fn] = mat
    return mapping


# --------------------------------------------------------------------------- #
# RQ1 metric 1: coverage
# --------------------------------------------------------------------------- #
def coverage_of(prepared: dict, workdir: Path) -> dict:
    """Line coverage of the PUT while the suite runs under SlipCover."""
    if prepared["style"] == "empty":
        return {"line_pct": 0.0, "lines_total": 0, "lines_covered": 0}
    out = workdir / "slipcover.json"
    if out.exists():
        out.unlink()
    env = dict(os.environ, PYTHONPATH=str(workdir), NO_COLOR="1",
               PYTEST_DISABLE_PLUGIN_AUTOLOAD="1")
    cmd = [BIN("slipcover"), "--branch", "--json", "--out", str(out),
           "-m", "pytest", "-q", "-p", "no:cacheprovider", "--no-header",
           "-o", "addopts="] + [p.name for p in prepared["pytest_files"]]
    try:
        _run(cmd, workdir, env, 300)
    except (subprocess.TimeoutExpired, FileNotFoundError):
        return {"line_pct": None, "lines_total": 0, "lines_covered": 0}
    if not out.exists():
        return {"line_pct": None, "lines_total": 0, "lines_covered": 0}
    put_name = prepared["put"].name
    covered = missing = 0
    branch_covered = branch_missing = 0
    for key, info in json.loads(out.read_text()).get("files", {}).items():
        if Path(key).name != put_name:
            continue
        s = info.get("summary", {})
        covered += s.get("covered_lines", 0)
        missing += s.get("missing_lines", 0)
        branch_covered += s.get("covered_branches", 0)
        branch_missing += s.get("missing_branches", 0)
    total = covered + missing
    branches = branch_covered + branch_missing
    return {"line_pct": 100.0 * covered / total if total else 0.0,
            "branch_pct": 100.0 * branch_covered / branches if branches else None,
            "lines_total": total, "lines_covered": covered}


# --------------------------------------------------------------------------- #
# RQ1 metric 2: pass rate
# --------------------------------------------------------------------------- #
def pass_rate_of(prepared: dict, workdir: Path) -> dict:
    """Passing test units / total test units, each unit executed alone."""
    env = dict(os.environ, PYTHONPATH=str(workdir), NO_COLOR="1",
               PYTEST_DISABLE_PLUGIN_AUTOLOAD="1")
    owner = _alias_owner(prepared)
    total = ok = 0
    for _orig, fn in prepared["units"]:
        mat = owner.get(fn) or (prepared["pytest_files"][0] if prepared["pytest_files"] else None)
        if mat is None:
            continue
        target = "{0}::{1}".format(mat.name, fn) if fn else mat.name
        total += 1
        try:
            cp = _run([PY, PYTEST, "-q", "-p", "no:cacheprovider", "--no-header",
                       "-o", "addopts=", target], workdir, env, 120)
            text = cp.stdout + cp.stderr
            passed = _count(r"(\d+) passed", text)
            bad = _count(r"(\d+) failed", text) + _count(r"(\d+) error", text)
            collected = _count(r"collected (\d+)", text)
            if passed >= 1 and bad == 0:
                ok += 1
            elif fn == "" and cp.returncode == 0 and collected != 0:
                ok += 1
        except subprocess.TimeoutExpired:
            pass
    return {"pass_rate": 100.0 * ok / total if total else None,
            "n_tests": total, "n_passed": ok}


# --------------------------------------------------------------------------- #
# RQ1 metric 3: mutation score
# --------------------------------------------------------------------------- #
def generate_mutants(put: Path, outdir: Path, workdir: Path) -> T.List[Path]:
    """Create mutants with MutPy for PUTs that ship without any."""
    outdir.mkdir(parents=True, exist_ok=True)
    for stale in outdir.glob("mutant_*.py"):
        stale.unlink()
    env = dict(os.environ, PYTHONPATH=str(put.parent))
    try:
        _run([BIN("mut.py"), "--target", str(put), "--output-dir", str(outdir),
              "--force"], workdir, env, 300)
    except (subprocess.TimeoutExpired, FileNotFoundError):
        pass
    return sorted(outdir.glob("mutant_*.py"))


def mutation_score_of(prepared: dict, mutants: T.Sequence[Path], workdir: Path,
                      timeout: float = 10.0) -> dict:
    """MuTAP-style mutation score over `mutants`.

    inline suites: mutant source + the suite's test part, executed as a script,
                   i.e. what MuTAP's Mutation_Score.py does;
    import suites: the mutant shadows the PUT on PYTHONPATH while pytest runs.
    """
    mutants = [Path(m) for m in mutants]
    limit_raw = os.getenv("EVAL_MUTANT_LIMIT", "0").strip()
    if limit_raw and limit_raw not in {"0", "none", "all"}:
        mutants = mutants[:max(0, int(limit_raw))]
    if prepared["style"] == "empty" or not mutants:
        return {"mutation_score": None, "killed": 0, "survived": 0,
                "problematic": 0, "n_mutants": len(mutants)}

    env = dict(os.environ, NO_COLOR="1",
               PYTEST_DISABLE_PLUGIN_AUTOLOAD="1")
    inline = prepared["style"] == "inline"
    shadow = workdir / "mut_shadow"
    if inline:
        env["PYTHONPATH"] = str(workdir)
    else:
        shadow.mkdir(parents=True, exist_ok=True)
        env["PYTHONPATH"] = "{0}:{1}".format(shadow, workdir)

    killed = survived = problematic = 0
    tmp = Path(tempfile.mkdtemp(dir=workdir))
    try:
        for mut in mutants:
            try:
                mut_src = mut.read_text(errors="ignore")
            except OSError:
                problematic += 1
                continue
            if inline:
                calls = "\n".join("{0}()".format(fn)
                                  for part in prepared["inline_parts"]
                                  for fn in TEST_DEF.findall(part))
                probe = tmp / "mut_probe.py"
                probe.write_text(mut_src + "\n\n"
                                 + "\n\n".join(prepared["inline_parts"])
                                 + "\n\n" + calls + "\n")
                cmd: T.List[str] = [PY, str(probe)]
                cwd = tmp
            else:
                (shadow / prepared["put"].name).write_text(mut_src)
                cmd = [PY, PYTEST, "-q", "-p", "no:cacheprovider", "--no-header",
                       "-o", "addopts="] + [p.name for p in prepared["pytest_files"]]
                cwd = workdir
            try:
                cp = _run(cmd, cwd, env, timeout)
                text = cp.stdout + cp.stderr
                if cp.returncode == 0:
                    survived += 1
                elif "AssertionError" in text:
                    killed += 1
                else:
                    problematic += 1
            except subprocess.TimeoutExpired:
                problematic += 1
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    denom = killed + survived
    return {"mutation_score": 100.0 * killed / denom if denom else None,
            "killed": killed, "survived": survived, "problematic": problematic,
            "n_mutants": denom + problematic}


# --------------------------------------------------------------------------- #
# RQ2: CoverUp runner (source of wall time and cost)
# --------------------------------------------------------------------------- #
@dataclass
class CoverupRun:
    ok: bool = False
    wall_time_s: float = 0.0
    cost_usd: float = 0.0
    good: int = 0
    failed: int = 0
    useless: int = 0
    retries: int = 0
    error: str = ""
    generated_tests: T.List[str] = field(default_factory=list)


def run_coverup(put: Path, tests_dir: Path, workdir: Path, model: str = "gpt-4o",
                timeout: int = 900, extra: T.Sequence[str] = ()) -> CoverupRun:
    """Run CoverUp from scratch over `put`, returning wall time and native cost."""
    # CoverUp resolves --tests-dir/--source against its own cwd, so everything
    # handed to it must be absolute.
    workdir = Path(workdir).resolve()
    tests_dir = Path(tests_dir).resolve()
    workdir.mkdir(parents=True, exist_ok=True)
    # SlipCover only traces files under the working directory, so the PUT is
    # copied in and CoverUp is pointed at that copy.
    local_put = workdir / Path(put).name
    if Path(put).resolve() != local_put.resolve():
        shutil.copy(put, local_put)
    tests_dir.mkdir(parents=True, exist_ok=True)
    # A rerun must start from the original test baseline, not retain generated
    # CoverUp tests or a completed checkpoint from an earlier invocation.
    for stale in tests_dir.glob("test_coverup_*.py"):
        stale.unlink()
    ckpt = workdir / "coverup.checkpoint"
    if ckpt.exists():
        ckpt.unlink()
    # "from scratch" means no pre-existing tests, but the module must still be
    # imported so that SlipCover reports its lines as *uncovered* instead of
    # silently reporting 100% over an empty suite.
    (tests_dir / "conftest.py").write_text("import {0}  # noqa: F401\n".format(local_put.stem))
    cmd = [BIN("coverup"), "--tests-dir", str(tests_dir), str(put),
           "--model", model, "--checkpoint", str(ckpt),
           "--log-file", str(workdir / "coverup.log"),
           "--no-isolate-tests", "--no-repeat-tests", "--no-disable-polluting",
           "--no-disable-failing", "--max-attempts", "3", *extra]
    cmd[cmd.index(str(put))] = str(local_put)
    env = dict(os.environ, PYTHONPATH=str(workdir), NO_COLOR="1",
               PYTEST_DISABLE_PLUGIN_AUTOLOAD="1")
    r = CoverupRun()
    t0 = time.perf_counter()
    try:
        cp = subprocess.run(cmd, cwd=str(workdir), env=env, capture_output=True,
                            text=True, timeout=timeout)
        r.ok = cp.returncode == 0
        r.error = (cp.stdout + cp.stderr)[-2000:]
    except subprocess.TimeoutExpired:
        r.error = "timeout after {}s".format(timeout)
    except FileNotFoundError as e:
        r.error = "coverup not found: {}".format(e)
    r.wall_time_s = time.perf_counter() - t0
    r.generated_tests = [str(p) for p in sorted(tests_dir.glob("test_coverup_*.py"))]
    if ckpt.exists():
        try:
            ck = json.loads(ckpt.read_text())
            r.cost_usd = float(ck.get("cost", 0.0))
            ctr = ck.get("counters", {})
            r.good, r.failed = ctr.get("G", 0), ctr.get("F", 0)
            r.useless, r.retries = ctr.get("U", 0), ctr.get("R", 0)
        except (json.JSONDecodeError, ValueError, AttributeError) as e:
            r.error += " | checkpoint unreadable: {}".format(e)
    return r


# --------------------------------------------------------------------------- #
# One task, end to end
# --------------------------------------------------------------------------- #
def evaluate(dataset: str, task: str, tests: T.Sequence[Path], method: str,
             *, wall_time_s: float | None = None, cost_usd: float | None = None,
             workroot: Path | None = None) -> dict:
    """Measure the RQ1/RQ2 metrics of `tests` against the task's PUT."""
    layout = LAYOUTS[dataset](task)
    workdir = Path(tempfile.mkdtemp(prefix="{0}_{1}_".format(dataset, task),
                                   dir=str(workroot) if workroot else None))
    row: T.Dict[str, T.Any] = {"dataset": dataset, "task": str(task),
                               "method": method, "put": Path(layout["put"]).name}
    try:
        if not Path(layout["put"]).exists():
            row["error"] = "PUT missing"
            return row
        prepared = prepare_suite(layout, tests, workdir)
        row.update(coverage_of(prepared, workdir))
        row.update(pass_rate_of(prepared, workdir))
        mutants = list(layout["mutants"]) or generate_mutants(
            prepared["put"], workdir / "mutants", workdir)
        row.update(mutation_score_of(prepared, mutants, workdir))
        row["n_tests_files"] = len(prepared["pytest_files"])
        if wall_time_s is not None:
            row["wall_time_s"] = round(wall_time_s, 2)
        if cost_usd is not None:
            row["cost_usd"] = round(cost_usd, 5)
    finally:
        shutil.rmtree(workdir, ignore_errors=True)
    return row