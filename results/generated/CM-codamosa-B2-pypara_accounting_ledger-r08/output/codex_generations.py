# Unit test for function build_general_ledger
def test_build_general_ledger():
    from types import SimpleNamespace
    from typing import cast

    since = datetime.date(2024, 1, 1)
    until = datetime.date(2024, 1, 31)
    period = DateRange(since, until)

    cash = cast(Account, "cash")
    equity = cast(Account, "equity")
    revenue = cast(Account, "revenue")
    excluded = cast(Account, "excluded")

    debit = SimpleNamespace(value=1)
    credit = SimpleNamespace(value=-1)

    def journal_entry(date, *postings):
        return SimpleNamespace(date=date, postings=list(postings))

    def posting(account, amount, direction):
        return SimpleNamespace(
            account=account,
            amount=Amount(Decimal(amount)),
            direction=direction,
        )

    initial = {
        cash: Balance(since, Quantity(Decimal("100.00"))),
        equity: Balance(since, Quantity(Decimal("-100.00"))),
    }

    journal = [
        # Excluded because it is before the accounting period.
        journal_entry(
            since - datetime.timedelta(days=1),
            posting(excluded, "999.00", debit),
        ),
        # Period boundaries are inclusive.
        journal_entry(
            since,
            posting(cash, "25.00", debit),
        ),
        journal_entry(
            datetime.date(2024, 1, 15),
            posting(cash, "10.00", credit),
            posting(revenue, "40.00", credit),
        ),
        journal_entry(
            until,
            posting(cash, "5.00", debit),
        ),
        # Excluded because it is after the accounting period.
        journal_entry(
            until + datetime.timedelta(days=1),
            posting(excluded, "999.00", debit),
        ),
    ]

    result = module_0.build_general_ledger(period, journal, initial)

    assert result.period == period
    assert set(result.ledgers) == {cash, equity, revenue}
    assert excluded not in result.ledgers

    cash_ledger = result.ledgers[cash]
    assert cash_ledger.account == cash
    assert cash_ledger.initial == initial[cash]

