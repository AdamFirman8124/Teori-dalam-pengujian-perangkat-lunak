def test_DashSegmentsFD_real_download():
    class TestDashSegmentsFD(DashSegmentsFD):
        def __init__(self):
            self.params = {
                'fragment_retries': 1,
                'skip_unavailable_fragments': True,
            }
            self.download_calls = []
            self.appended_fragments = []
            self.retry_calls = []
            self.prepared_ctx = None
            self.finished_ctx = None

        def _prepare_and_start_frag_download(self, ctx):
            ctx['fragment_index'] = 0
            self.prepared_ctx = ctx

        def _download_fragment(self, ctx, fragment_url, info_dict):
            self.download_calls.append((ctx, fragment_url, info_dict))

            # Simulate a transient HTTP failure for the first fragment.
            if len(self.download_calls) == 1:
                raise compat_urllib_error.HTTPError(
                    fragment_url, 404, 'Not Found', None, None)

            return True, ('content:%s' % fragment_url).encode('utf-8')

        def _append_fragment(self, ctx, frag_content):
            self.appended_fragments.append(frag_content)
            ctx['fragment_index'] += 1

        def _finish_frag_download(self, ctx):
            self.finished_ctx = ctx

        def report_retry_fragment(
                self, err, frag_index, retry_count, fragment_retries):
            self.retry_calls.append(
                (err.code, frag_index, retry_count, fragment_retries))

        def report_skip_fragment(self, frag_index):
            raise AssertionError(
                'Fragment %d should not have been skipped' % frag_index)

        def report_error(self, message):
            raise AssertionError('Unexpected error: %s' % message)

    info_dict = {
        'fragment_base_url': 'https://example.com/video/',
        'fragments': [
            {'path': 'init.m4s'},
            {'url': 'https://cdn.example.com/media.m4s'},
        ],
    }

    fd = TestDashSegmentsFD()

    assert fd.real_download('output.mp4', info_dict) is True

    assert fd.prepared_ctx['filename'] == 'output.mp4'
    assert fd.prepared_ctx['total_frags'] == 2
    assert fd.finished_ctx is fd.prepared_ctx
    assert fd.finished_ctx['fragment_index'] == 2

