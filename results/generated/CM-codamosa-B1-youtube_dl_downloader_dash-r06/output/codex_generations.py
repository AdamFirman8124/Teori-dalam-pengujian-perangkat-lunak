def test_DashSegmentsFD_real_download():
    fd = DashSegmentsFD.__new__(DashSegmentsFD)
    fd.params = {
        'test': False,
        'fragment_retries': 0,
        'skip_unavailable_fragments': True,
    }

    prepared = []
    downloaded = []
    appended = []
    finished = []

    def prepare(ctx):
        ctx['fragment_index'] = 0
        prepared.append(ctx)

    def download(ctx, url, info_dict):
        downloaded.append((ctx, url, info_dict))
        return True, ('fragment-%d' % len(downloaded)).encode('ascii')

    def append(ctx, content):
        appended.append((ctx, content))

    def finish(ctx):
        finished.append(ctx)

    fd._prepare_and_start_frag_download = prepare
    fd._download_fragment = download
    fd._append_fragment = append
    fd._finish_frag_download = finish

    info_dict = {
        'fragment_base_url': 'https://cdn.example.test/media/',
        'fragments': [
            {'path': 'init.mp4'},
            {'url': 'https://cdn.example.test/media/segment-1.m4s'},
        ],
    }

    result = fd.real_download('output.mp4', info_dict)

    assert result is True
    assert len(prepared) == 1

    ctx = prepared[0]
    assert ctx == {
        'filename': 'output.mp4',
        'total_frags': 2,
        'fragment_index': 0,
    }

    assert [item[1] for item in downloaded] == [
        'https://cdn.example.test/media/init.mp4',
        'https://cdn.example.test/media/segment-1.m4s',
    ]
    assert all(item[0] is ctx for item in downloaded)
    assert all(item[2] is info_dict for item in downloaded)

    assert appended == [
        (ctx, b'fragment-1'),
        (ctx, b'fragment-2'),
    ]
    assert finished == [ctx]

