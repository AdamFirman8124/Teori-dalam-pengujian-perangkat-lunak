    task.args = {
        'argument_spec': argument_spec,
        'provided_arguments': {'name': 'web', 'port': '8080'},
        'validate_args_context': {'type': 'role', 'name': 'myrole'},
    }
    task.check_mode = False
    task.async_val = False

