    # The special "vars" mapping is returned without templating.
    templar.template.reset_mock()
    assert variables["vars"] is raw_vars
    templar.template.assert_not_called()

    # Unsafe values are also returned without templating.
    assert variables["unsafe"] is unsafe_value
    templar.template.assert_not_called()

    # HostVars objects are returned without templating.
    with patch("ansible.vars.hostvars.HostVars", DummyHostVars):
        assert variables["hostvars"] is hostvars
    templar.template.assert_not_called()

    # Missing names raise KeyError.
    with pytest.raises(KeyError, match="undefined variable: absent"):
        variables["absent"]

    # Undefined-variable errors include the original variable value.
    available_variables["undefined"] = "{{ missing }}"
    templar.template.side_effect = AnsibleUndefinedVariable("missing")
