# Unit test for method __getitem__ of class AnsibleJ2Vars
def test_AnsibleJ2Vars___getitem__():
    import pytest

    undefined_value = object()
    invalid_value = object()

    class UnsafeValue(object):
        __UNSAFE__ = True

    unsafe_value = UnsafeValue()
    vars_value = {'answer': 42}

    class DummyTemplar(object):
        def __init__(self):
            self.available_variables = {
                'templated': 'source value',
                'shared': 'available value',
                'vars': vars_value,
                'unsafe': unsafe_value,
                'undefined': undefined_value,
                'invalid': invalid_value,
            }
            self.template_calls = []

        def template(self, value):
            self.template_calls.append(value)

            if value is undefined_value:
                raise AnsibleUndefinedVariable('nested variable is undefined')
            if value is invalid_value:
                raise ValueError('templating failed')

            return 'rendered: %s' % value

    templar = DummyTemplar()
    variables = AnsibleJ2Vars(
        templar,
        globals={
            'global_only': 'global value',
            'shared': 'global value',
        },
        locals={
            'local_only': 'local value',
            'shared': 'local value',
        },
    )

    # Locals have the highest precedence and are returned without templating.
    assert variables['local_only'] == 'local value'
    assert variables['shared'] == 'local value'
    assert templar.template_calls == []

    # Available variables are templated before being returned.
    assert variables['templated'] == 'rendered: source value'
    assert templar.template_calls == ['source value']

    # Globals are used when the name is absent from locals and available vars.
    assert variables['global_only'] == 'global value'
    assert templar.template_calls == ['source value']

    # The special "vars" dictionary and unsafe values must not be templated.
    assert variables['vars'] is vars_value
    assert variables['unsafe'] is unsafe_value
    assert templar.template_calls == ['source value']

    # Missing variables raise KeyError.
    with pytest.raises(KeyError, match='undefined variable: does_not_exist'):
        variables['does_not_exist']

    # AnsibleUndefinedVariable is re-raised with variable context.
    with pytest.raises(AnsibleUndefinedVariable) as exc_info:
        variables['undefined']
    assert 'nested variable is undefined' in to_native(exc_info.value)

    # Other templating failures are wrapped in AnsibleError.
    with pytest.raises(AnsibleError) as exc_info:
        variables['invalid']
    error = to_native(exc_info.value)
    assert 'An unhandled exception occurred while templating' in error
    assert 'templating failed' in error

