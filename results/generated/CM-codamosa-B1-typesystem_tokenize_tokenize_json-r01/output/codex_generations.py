def test_tokenize_json_object():
    token = module_0.tokenize_json('{"a": 1}')
    assert isinstance(token, DictToken)
    assert token.value == {"a": 1}
    # Token spans the full string: start at '{', end at '}'
    assert token.start == 0
    assert token.end == 7


def test_tokenize_json_array():
    token = module_0.tokenize_json("[1, 2, 3]")
    assert isinstance(token, ListToken)
    assert token.value == [1, 2, 3]


def test_tokenize_json_scalar_string():
    token = module_0.tokenize_json('"hello"')
    assert isinstance(token, ScalarToken)
    assert token.value == "hello"


def test_tokenize_json_scalar_keywords_and_numbers():
    assert module_0.tokenize_json("null").value is None
    assert module_0.tokenize_json("true").value is True
    assert module_0.tokenize_json("false").value is False
    assert module_0.tokenize_json("42").value == 42
    assert module_0.tokenize_json("-1.5e3").value == -1500.0


def test_tokenize_json_bytes_input():
    token = module_0.tokenize_json(b'{"key": "value"}')
