def test_ActionModule_run():import pytest
from unittest.mock import MagicMock, patch

from ansible.errors import AnsibleError
from ansible.plugins.action.validate_argument_spec import ActionModule


def _make_action(task_args, templar_return=None):
    """Build an ActionModule with mocked internals."""
    action = ActionModule(
        task=MagicMock(args=task_args),
        connection=MagicMock(),
        play_context=MagicMock(),
        loader=MagicMock(),
        templar=MagicMock(),
        shared_loader_obj=MagicMock(),
    )
    # _templar.template() returns args unchanged
    action._templar.template.side_effect = lambda x: x
    return action


def test_run_passes_validation():
    task_args = {
        'argument_spec': {'name': {'type': 'str', 'required': True}},
        'provided_arguments': {'name': 'web01'},
    }
    action = _make_action(task_args)
    result = action.run(task_vars={})

    assert result['failed'] is not True
    assert result['changed'] is False
    assert result['msg'] == 'The arg spec validation passed'


def test_run_fails_on_missing_required():
    task_args = {
        'argument_spec': {'name': {'type': 'str', 'required': True}},
        'provided_arguments': {},
    }
    action = _make_action(task_args)
    result = action.run(task_vars={})

    assert result['failed'] is True
    assert 'argument_errors' in result
    assert 'Validation of arguments failed' in result['msg']


def test_run_missing_argument_spec_raises():
    action = _make_action({})
    with pytest.raises(AnsibleError, match='"argument_spec" arg is required'):
        action.run(task_vars={})


def test_run_wrong_type_argument_spec_raises():
    action = _make_action({'argument_spec': ['not', 'a', 'dict']})
    with pytest.raises(AnsibleError, match='Incorrect type for argument_spec'):
        action.run(task_vars={})


def test_run_args_from_task_vars_are_used():
    task_args = {
        'argument_spec': {'name': {'type': 'str', 'required': True}},
        'provided_arguments': {},
    }
    action = _make_action(task_args)
    result = action.run(task_vars={'name': 'from-vars'})

    assert result['failed'] is not True


def test_run_validate_args_context_passthrough():
    ctx = {'name': 'my_role', 'argument_specs': {}}
    task_args = {
        'argument_spec': {'name': {'type': 'str'}},
        'provided_arguments': {'name': 'x'},
        'validate_args_context': ctx,
    }
    action = _make_action(task_args)
    result = action.run(task_vars={})

    assert result['validate_args_context'] == ctx

