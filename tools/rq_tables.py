"""Build RQ1/RQ2 markdown tables from a rows.csv produced by an experiment run.

    .venv/bin/python tools/rq_tables.py experiment_results/rows.csv [outdir]

  RQ1 groups by METHOD      -> Coverage / Pass Rate / Mutation Score
  RQ2 groups by BACKBONE    -> Coverage / Pass Rate / Time / Cost

The RQ2 backbone collapses LiteLLM transport prefixes (openai/gpt-5.5 -> gpt-5.5)
so the same model generated by different methods is compared together.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))
import run_experiment as rx  # noqa: E402

rows_csv = Path(sys.argv[1]).resolve()
outdir = Path(sys.argv[2]).resolve() if len(sys.argv) > 2 else rows_csv.parent
outdir.mkdir(parents=True, exist_ok=True)

numeric = ("line_pct", "branch_pct", "pass_rate", "mutation_score",
           "wall_time_s", "cost_usd")
rows: list[dict] = []
for raw in csv.DictReader(rows_csv.open()):
    row: dict = dict(raw)
    for col in numeric:
        val = raw.get(col, "")
        row[col] = float(val) if val not in ("", None) else None
    rows.append(row)

by_method: dict[str, list[dict]] = {}
for r in rows:
    by_method.setdefault(r.get("method") or "unknown", []).append(r)

by_backbone: dict[str, list[dict]] = {}
for r in rows:
    backbone = rx.backbone_name(r.get("model")) or r.get("method") or "unknown"
    by_backbone.setdefault(backbone, []).append(r)

rq1 = rx.table(by_method,
               "RQ1 - Main performance (Coverage / Pass Rate / Mutation Score)",
               ["line_pct", "pass_rate", "mutation_score"])
rq2 = rx.table(by_backbone,
               "RQ2 - Backbone (Coverage / Pass Rate / Time / Cost)",
               ["line_pct", "pass_rate", "wall_time_s", "cost_usd"],
               first_col="backbone")

(outdir / "rq1.md").write_text(rq1)
(outdir / "rq2.md").write_text(rq2)
print(rq1)
print(rq2)
print("wrote", outdir / "rq1.md", "and", outdir / "rq2.md")
