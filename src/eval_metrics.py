def _py_files(d: Path) -> T.List[Path]:
    if not d.exists():
        return []
    return sorted(p for p in d.rglob("*.py") if p.stem != "__init__")


def _first_match(globs: T.Sequence[T.Iterable[Path]]) -> T.List[Path]:
    """Files of the first glob that yields anything: suite names vary per task."""
    for g in globs:
        found = sorted(g)
        if found:
            return found
    return []


