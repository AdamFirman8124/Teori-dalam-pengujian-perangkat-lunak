"""Measurement harness for CoverUp experiments on the two MuTAP datasets.

Metrics requested:
  RQ1 (main performance): Coverage, Pass Rate, Mutation Score
  RQ2 (backbone)        : Coverage, Pass Rate, Wall time and Cost

The harness is method-agnostic: it measures ANY test suite against ANY
Program-Under-Test (PUT), so it works for suites generated by CoverUp and for
the baselines shipped with the datasets (MuTAP/Codex, Copilot, Pynguin).

Two suite styles occur in these datasets and are handled transparently:
  * inline - MuTAP/Codex/Copilot files that embed the PUT source, define
             ``def test():`` and never call it (MuTAP runs that test part
             against each mutant);
  * import - CoverUp/Pynguin/pytest files that import the module under test.

Metric definitions, applied identically to every method:
  Coverage       Share of the PUT's executable lines executed by the suite,
                 measured with SlipCover (the instrumenter CoverUp uses),
                 restricted to the PUT file.
  Pass Rate      Passing test units / total test units.  Every test function
                 runs in isolation so one broken test cannot mask the others.
  Mutation Score killed / (killed + survived), i.e. MuTAP's protocol with the
                 problematic mutants excluded from the denominator.  A mutant is
                 killed when the suite fails on an assertion, survives when it
                 runs clean, is "broken" when the suite errors for a non-assertion
                 reason, and "timeout" when it exceeds the per-mutant limit.
                 Broken/timeout mutants are reported separately and excluded from
                 the score.  Every row also carries a ``mutant_set_id`` (stable
                 hash of the exact mutant set) and ``mutant_set_total`` so
                 methods and models are always compared on the identical mutant
                 set.
  Wall time      Generation time of the suite (CoverUp run).  For pre-existing
                 baseline suites it is intentionally left empty rather than
                 conflated with evaluation time.
  Cost           USD as accounted by CoverUp itself (litellm completion_cost,
                 persisted in CoverUp's checkpoint file).
"""

