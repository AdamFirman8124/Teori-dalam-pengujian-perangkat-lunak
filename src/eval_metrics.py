def BIN(name: str) -> str:
    """Return a runnable project executable on both POSIX and Windows.

    The repository may contain a stale Linux ``.venv/bin`` copied from another
    machine.  On Windows those text launcher files are not executable, so
    prefer the active interpreter/user scripts or PATH instead.
    """
    if name == "python":
        return sys.executable

    candidates = []
    if os.name == "nt":
        script_dirs = [
            VENV / "Scripts",
            Path(sysconfig.get_path("scripts")),
        ]
        for base in (site.getusersitepackages(), site.getuserbase()):
            if base:
                script_dirs.extend([
                    Path(base).parent / "Scripts",
                    Path(base) / "Scripts",
                ])
        for script_dir in script_dirs:
            candidates.extend([
                script_dir / (name + ".exe"),
                script_dir / name,
            ])
        for candidate in candidates:
            if candidate.exists() and candidate.suffix == ".exe":
                return str(candidate)
    else:
        candidate = VENV / "bin" / name
        if candidate.exists():
            return str(candidate)
    return shutil.which(name) or name


