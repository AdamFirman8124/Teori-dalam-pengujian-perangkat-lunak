def _count(pattern: str, text: str) -> int:
    m = re.search(pattern, text)
    return int(m.group(1)) if m else 0



def pytest_outcome(text: str) -> str:
    """Classify one pytest/pytest-style run as passed/failed/error/timeout.

    The last line that looks like a pytest summary is authoritative, and its
    numeric counters decide the outcome.  This replaces the historical
    heuristic of checking whether ``"AssertionError"`` or ``" failed"`` appears
    anywhere in the output, which would falsely fire on a *passing* test that
    merely contains those substrings (e.g. ``pytest.raises(AssertionError)``).

    Outcomes:
      passed  - ran clean (including "no tests ran")
      failed  - at least one failure with no collection/teardown error
      error   - collection/import/usage error, or unrecognisable output
      timeout - the run exceeded its per-mutant limit
    """
    if "timed out" in text.lower():
        return "timeout"

    summary = ""
    for line in text.splitlines():
        low = line.lower()
        if any(kw in low for kw in ("passed", "failed", "error", "tests ran")):
            summary = low

    def _count_in(source: str, word: str) -> int:
        m = re.search(r"(\d+)\s+" + word, source)
        return int(m.group(1)) if m else 0

    if summary:
        errors = _count_in(summary, "error") + _count_in(summary, "errors")
        failures = _count_in(summary, "failed")
        passes = _count_in(summary, "passed")
        if errors:
            return "error"
        if failures:
            return "failed"
        if passes or "no tests ran" in summary or "tests ran" in summary:
            return "passed"
        # Summary had a keyword but no extractable counts (e.g. a bare
        # "FAILED test_x.py::test_y" line).
        if "error" in summary:
            return "error"
        if "failed" in summary:
            return "failed"
        return "passed"

    # No recognisable summary at all: fall back to counting elsewhere.
    failed = _count(r"(\d+) failed", text)
    errors = _count(r"(\d+) error", text)
    passed = _count(r"(\d+) passed", text)
    if not (failed or errors or passed):
        # No counters; search for the strongest keyword.
        low = text.lower()
        if "error" in low:
            return "error"
        if "failed" in low:
            return "failed"
        return "error"
    if errors:
        return "error"
    return "failed" if failed else "passed"


def _resolve_cmd(cmd) -> T.List[str]:
    """Resolve module-based or filesystem commands to a runnable command."""
    parts = [str(c) for c in cmd]
    if len(parts) >= 2 and parts[0] == PY and parts[1] == "-m":
        return parts
    executable = parts[0]
    if not Path(executable).exists():
        executable = BIN(executable)
    return [executable] + parts[1:]


def _run(cmd, cwd: Path, env: dict, timeout: float):
    return subprocess.run(_resolve_cmd(cmd), cwd=str(cwd), env=env,
                          capture_output=True, text=True, encoding="utf-8",
                          errors="replace", timeout=timeout)


def coverup_cmd() -> T.List[str]:
    """Runnable CoverUp CLI, independent from shell PATH.

    Prefer the repository checkout when CoverUp is not installed.  The project
    uses a ``src`` layout, so merely running from the repository root does not
    make the package importable by a child process.
    """
    try:
        import coverup  # noqa: F401
        return [PY, "-m", "coverup"]
    except ImportError:
        local_source = ROOT / "coverup" / "src" / "coverup" / "coverup.py"
        if local_source.exists():
            return [PY, "-m", "coverup"]
        return [BIN("coverup")]


def coverup_pythonpath() -> T.List[str]:
    """Return local CoverUp source paths needed by a subprocess."""
    local_source = ROOT / "coverup" / "src"
    return [str(local_source)] if (local_source / "coverup").is_dir() else []


def coverup_rate_limit() -> T.List[str]:
    """Return the ``--rate-limit`` arguments for CoverUp, if configured.

    CoverUp throttles only models listed in its own ``MODEL_RATE_LIMITS`` table.
    For a gateway model such as ``gpt-5.6-*`` that table yields ``None``, so
    every request fires immediately and the provider answers HTTP 429
    ("Rate limit: 50 rpm").  Measurements on 2026-10-15 lost 35% of CoverUp
    tasks (59/169) that way.

    ``COVERUP_RATE_LIMIT`` sets the prompt token budget per minute, passed
    straight through to ``coverup --rate-limit`` (an ``AsyncLimiter`` window of
    60s).  Leave it empty/0 to keep CoverUp's built-in behaviour.
    """
    raw = (os.getenv("COVERUP_RATE_LIMIT") or "").strip()
    if not raw:
        return []
    try:
        limit = int(float(raw))
    except ValueError:
        return []
    return ["--rate-limit", str(limit)] if limit > 0 else []


