TEST_DEF = re.compile(r"^def (test\w*)\(", re.M)


def test_functions(tf: Path) -> T.List[str]:
    """Module-level names that pytest would collect as tests."""
    try:
        tree = ast.parse(tf.read_text())
    except (SyntaxError, OSError, UnicodeDecodeError):
        return []
    return [n.name for n in tree.body
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
            and n.name.startswith("test")]


def _inline_test_part(src: str) -> str:
    """Test part of a MuTAP-style file: everything from the first test def."""
    m = TEST_DEF.search(src)
    return src[m.start():] if m else ""


def _handler_swallows_failures(handler: ast.ExceptHandler) -> bool:
    """Whether an except handler can turn a test failure into a pass."""
    if handler.type is None:
        catches_failure = True
    else:
        names: T.Set[str] = set()
        for node in ast.walk(handler.type):
            if isinstance(node, ast.Name):
                names.add(node.id)
            elif isinstance(node, ast.Attribute):
                names.add(node.attr)
        catches_failure = bool(names & {"BaseException", "Exception", "AssertionError"})
    if not catches_failure:
        return False
    return all(isinstance(stmt, (ast.Pass, ast.Expr)) for stmt in handler.body)


def suite_validity(path: Path) -> T.Tuple[bool, str, int]:
    """Validate that a generated suite has executable, meaningful test units.

    Comment-only/header-only files and tests that suppress assertions via broad
    ``except ...: pass`` are invalid.  Returning the assertion count also lets
    callers report the number of checks that can genuinely be evaluated.
    """
    try:
        source = Path(path).read_text(encoding="utf-8")
        tree = ast.parse(source, filename=str(path))
    except (OSError, UnicodeError, SyntaxError) as exc:
        return False, "unreadable or invalid Python ({})".format(type(exc).__name__), 0
    tests = [node for node in ast.walk(tree)
             if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
             and node.name.startswith("test")]
    if not tests:
        return False, "no test functions (empty/comment-only suite)", 0
    swallowed = [node.name for node in tests for child in ast.walk(node)
                 if isinstance(child, ast.Try)
                 and any(_handler_swallows_failures(h) for h in child.handlers)]
    if swallowed:
        return False, "test failures are swallowed by broad except/pass: {}".format(
            ", ".join(sorted(set(swallowed)))), 0
    _checked: T.Set[int] = set()
    for node in tests:
        for child in ast.walk(node):
            if _is_assertion(child):
                _checked.add(id(child))
            elif isinstance(child, (ast.With, ast.AsyncWith)):
                for item in child.items:
                    if _is_assertion_context(item):
                        _checked.add(id(item.context_expr))
    assertions = len(_checked)
    if assertions == 0:
        return False, "test functions contain no assertions", 0
    return True, "valid", assertions


def _is_assertion(node: ast.AST) -> bool:
    """Count an AST node as one executable check.

    Accepted oracles: the ``assert`` statement, pytest-style ``assert*`` helper
    calls, ``self.assert*`` unittest methods, and context managers such as
    ``with pytest.raises(...)`` / ``self.assertRaises(...)``.  The last two are
    real oracles that raise only when the expected exception/condition does not
    occur, so treating them as "no assertions" would wrongly discard valid
    suites.
    """
    if isinstance(node, ast.Assert):
        return True
    if not isinstance(node, ast.Call):
        return False
    func = node.func
    if isinstance(func, ast.Attribute) and func.attr.startswith("assert"):
        return True
    return False


def _is_assertion_context(node: ast.AST) -> bool:
    """Whether a ``With``/``AsyncWith`` item is an assertion context manager."""
    ctx = getattr(node, "context_expr", None)
    if not isinstance(ctx, ast.Call):
        return False
    func = ctx.func
    if isinstance(func, ast.Attribute) and func.attr.startswith(("assert", "raises")):
        return True
    return isinstance(func, ast.Name) and func.id in {"raises", "assertRaises"}


def mutant_set_metadata(mutants: T.Sequence[Path]) -> T.Dict[str, T.Any]:
    """Stable identity of the exact mutant set shared by every method/model."""
    paths = [Path(p) for p in mutants]
    digest = hashlib.sha256()
    for path in paths:
        digest.update(path.name.encode("utf-8", errors="replace"))
        digest.update(b"\0")
        try:
            digest.update(path.read_bytes())
        except OSError:
            digest.update(b"<unreadable>")
        digest.update(b"\0")
    return {"mutant_set_id": digest.hexdigest()[:16],
            "mutant_set_total": len(paths)}


def prepare_suite(layout: dict, tests: T.Sequence[Path], workdir: Path) -> dict:
    """Materialise `tests` in `workdir` so the PUT is importable, and classify them.

    Returns a dict with:
      style         "inline", "import" or "empty"
      pytest_files  materialised files pytest can collect
      units         [(original file, alias/function name or "")]
      inline_parts  raw test parts (for MuTAP-style mutation testing)
      put           the PUT file, copied into workdir
    """
    put_src = Path(layout["put"])
    put = workdir / put_src.name
    shutil.copy(put_src, put)
    tests = [Path(t) for t in tests if Path(t).exists()]
    if not tests:
        return {"style": "empty", "pytest_files": [], "units": [],
                "inline_parts": [], "put": put, "n_assertions": 0}

    validity = {t: suite_validity(t) for t in tests}
    invalid = ["{} ({})".format(t.name, result[1])
               for t, result in validity.items() if not result[0]]
    if invalid:
        raise ValueError("INVALID_GENERATED_TEST: " + "; ".join(invalid))
    assertion_count = sum(result[2] for result in validity.values())

    sources = {}
    for t in tests:
        sources[t] = t.read_text(errors="ignore")
    inline = [t for t in tests
              if ("import " + put.stem) not in sources[t]
              and ("from " + put.stem + " import") not in sources[t]
              and TEST_DEF.search(sources[t])]
    style = "inline" if inline else "import"

    pytest_files: T.List[Path] = []
    units: T.List[T.Tuple[Path, str]] = []
    inline_parts: T.List[str] = []

    for i, tf in enumerate(tests):
        if style == "inline" and tf in inline:
            part = _inline_test_part(sources[tf])
            fns = TEST_DEF.findall(part)
            if not fns:
                continue
            inline_parts.append(part)
            body = "from {0} import *  # noqa: F401,F403\n\n{1}\n\n".format(put.stem, part)
            for j, fn in enumerate(fns):
                alias = "test_wrapped_{0}".format(j)
                body += "def {0}():\n    {1}()\n\n".format(alias, fn)
                units.append((tf, alias))
            out = workdir / ("test_inline_{0}.py".format(i))
            out.write_text(body)
            pytest_files.append(out)
        else:
            dst = workdir / ("test_imported_{0}.py".format(i))
            shutil.copy(tf, dst)
            pytest_files.append(dst)
            for fn in test_functions(tf):
                units.append((tf, fn))
            if not test_functions(tf) and sources[tf].strip():
                units.append((tf, ""))
    return {"style": style, "pytest_files": pytest_files, "units": units,
            "inline_parts": inline_parts, "put": put,
            "n_assertions": assertion_count}


def _alias_owner(prepared: dict) -> T.Dict[str, Path]:
    """Map aliases created by prepare_suite back to their materialised file."""
    mapping: T.Dict[str, Path] = {}
    for mat in prepared["pytest_files"]:
        for fn in test_functions(mat):
            mapping[fn] = mat
    return mapping


# --------------------------------------------------------------------------- #
# RQ1 metric 1: coverage
# --------------------------------------------------------------------------- #
def coverage_of(prepared: dict, workdir: Path) -> dict:
    """Line coverage of the PUT while the suite runs under SlipCover."""
    if prepared["style"] == "empty":
        return {"line_pct": 0.0, "lines_total": 0, "lines_covered": 0}
    out = workdir / "slipcover.json"
    if out.exists():
        out.unlink()
    env = dict(os.environ, PYTHONPATH=str(workdir), NO_COLOR="1",
               PYTEST_DISABLE_PLUGIN_AUTOLOAD="1")
    cmd = [PY, "-m", "slipcover", "--branch", "--json", "--out", str(out),
           "-m", "pytest", "-q", "-p", "no:cacheprovider", "--no-header",
           "-o", "addopts="] + [p.name for p in prepared["pytest_files"]]
    try:
        _run(cmd, workdir, env, 300)
    except (subprocess.TimeoutExpired, FileNotFoundError):
        return {"line_pct": None, "lines_total": 0, "lines_covered": 0}
    if not out.exists():
        return {"line_pct": None, "lines_total": 0, "lines_covered": 0}
    put_name = prepared["put"].name
    covered = missing = 0
    branch_covered = branch_missing = 0
    for key, info in json.loads(out.read_text()).get("files", {}).items():
        if Path(key).name != put_name:
            continue
        s = info.get("summary", {})
        covered += s.get("covered_lines", 0)
        missing += s.get("missing_lines", 0)
        branch_covered += s.get("covered_branches", 0)
        branch_missing += s.get("missing_branches", 0)
    total = covered + missing
    branches = branch_covered + branch_missing
    return {"line_pct": 100.0 * covered / total if total else 0.0,
            "branch_pct": 100.0 * branch_covered / branches if branches else None,
            "lines_total": total, "lines_covered": covered}


# --------------------------------------------------------------------------- #
# RQ1 metric 2: pass rate
# --------------------------------------------------------------------------- #
def pass_rate_of(prepared: dict, workdir: Path) -> dict:
    """Passing test units / total test units, each unit executed alone.

    Every pytest invocation runs *from ``workdir``* (the per-evaluation job
    directory) and is handed explicit node ids, so pytest only ever collects
    the suite under test.  Running from a shared parent instead would let
    pytest's rootdir insertion discover test files left behind by earlier
    methods/models, mixing foreign units into ``n_tests`` (the source of the
    historical ``pass_rate=100, n_tests=2`` anomaly).
    """
    env = dict(os.environ, PYTHONPATH=str(workdir), NO_COLOR="1",
               PYTEST_DISABLE_PLUGIN_AUTOLOAD="1")
    owner = _alias_owner(prepared)
    total = ok = 0
    for _orig, fn in prepared["units"]:
        mat = owner.get(fn) or (prepared["pytest_files"][0] if prepared["pytest_files"] else None)
        if mat is None:
            continue
        target = "{0}::{1}".format(mat.name, fn) if fn else mat.name
        total += 1
        try:
            cp = _run([PY, PYTEST, PYTEST_MODULE, "-q", "-p", "no:cacheprovider",
                       "--no-header", "-o", "addopts=", target], workdir, env, 120)
            text = cp.stdout + cp.stderr
            passed = _count(r"(\d+) passed", text)
            bad = _count(r"(\d+) failed", text) + _count(r"(\d+) error", text)
            collected = _count(r"collected (\d+)", text)
            if passed >= 1 and bad == 0:
                ok += 1
            elif fn == "" and cp.returncode == 0 and collected != 0:
                ok += 1
        except subprocess.TimeoutExpired:
            pass
    return {"pass_rate": 100.0 * ok / total if total else None,
            "n_tests": total, "n_passed": ok,
            "n_assertions_evaluated": prepared.get("n_assertions", 0) if total else 0}


