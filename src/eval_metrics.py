def generate_mutants(put: Path, outdir: Path, workdir: Path) -> T.List[Path]:
    """Create mutants with MutPy for PUTs that ship without any."""
    outdir.mkdir(parents=True, exist_ok=True)
    for stale in outdir.glob("mutant_*.py"):
        stale.unlink()
    env = dict(os.environ, PYTHONPATH=str(put.parent))
    try:
        _run([BIN("mut.py"), "--target", str(put), "--output-dir", str(outdir),
              "--force"], workdir, env, 300)
    except (subprocess.TimeoutExpired, FileNotFoundError):
        pass
    return sorted(outdir.glob("mutant_*.py"))


def mutation_score_of(prepared: dict, mutants: T.Sequence[Path], workdir: Path,
                      timeout: float = 10.0) -> dict:
    """MuTAP-style mutation score over `mutants`.

    inline suites: mutant source + the suite's test part, executed as a script,
                   i.e. what MuTAP's Mutation_Score.py does;
    import suites: the mutant shadows the PUT on PYTHONPATH while pytest runs.
    """
    mutants = [Path(m) for m in mutants]
    limit_raw = os.getenv("EVAL_MUTANT_LIMIT", "0").strip()
    if limit_raw and limit_raw not in {"0", "none", "all"}:
        mutants = mutants[:max(0, int(limit_raw))]
    metadata = mutant_set_metadata(mutants)
    if prepared["style"] == "empty" or not mutants:
        return {"mutation_score": None, "killed": 0, "survived": 0,
                "broken": 0, "timeout": 0, "problematic": 0,
                "n_mutants": len(mutants), **metadata}

    base_env = dict(os.environ, NO_COLOR="1",
                    PYTEST_DISABLE_PLUGIN_AUTOLOAD="1")
    inline = prepared["style"] == "inline"
    calls = "\n".join("{0}()".format(fn)
                       for part in prepared["inline_parts"]
                       for fn in TEST_DEF.findall(part)) if inline else ""

    def evaluate_one(mut: Path) -> T.Tuple[int, int, int, int]:
        """Run one independent mutant in its own directory.

        The subprocesses do the CPU-heavy work, so threads let Windows overlap
        them without multiprocessing spawn/pickle issues.  Per-mutant
        directories prevent simultaneous shadow-module/probe writes from
        affecting one another.
        """
        jobdir = Path(tempfile.mkdtemp(prefix="mutant_", dir=str(workdir)))
        try:
            try:
                mut_src = mut.read_text(errors="ignore")
            except OSError:
                return 0, 0, 1, 0
            env = dict(base_env)
            if inline:
                probe = jobdir / "mut_probe.py"
                probe.write_text(mut_src + "\n\n"
                                 + "\n\n".join(prepared["inline_parts"])
                                 + "\n\n" + calls + "\n")
                cmd: T.List[str] = [PY, str(probe)]
                cwd = jobdir
                env["PYTHONPATH"] = str(workdir)
            else:
                # The mutant must shadow the PUT, but pytest inserts the
                # invocation cwd at sys.path[0].  If we ran from `workdir` the
                # real PUT there would win and every mutant would "survive".
                # Run from an isolated jobdir that holds the shadow package and
                # copies of the tests, so pytest's rootdir insertion is clean.
                shadow = jobdir / "mut_shadow"
                shadow.mkdir()
                (shadow / prepared["put"].name).write_text(mut_src)
                names = []
                for p in prepared["pytest_files"]:
                    shutil.copy(p, jobdir / p.name)
                    names.append(p.name)
                cmd = [PY, PYTEST, PYTEST_MODULE, "-q", "-p", "no:cacheprovider",
                       "--no-header", "-o", "addopts="] + names
                cwd = jobdir
                env["PYTHONPATH"] = os.pathsep.join((str(shadow), str(workdir)))
            try:
                cp = _run(cmd, cwd, env, timeout)
                text = (cp.stdout or "") + (cp.stderr or "")
                outcome = pytest_outcome(text)
                if cp.returncode == 0 and outcome != "failed":
                    return 0, 1, 0, 0          # survived: clean run
                if outcome == "failed":
                    return 1, 0, 0, 0          # killed: assertion failure
                if outcome == "timeout":
                    return 0, 0, 0, 1
                return 0, 0, 1, 0              # broken: import/collection error
            except subprocess.TimeoutExpired:
                return 0, 0, 0, 1
        finally:
            shutil.rmtree(jobdir, ignore_errors=True)

    workers_raw = os.getenv("EVAL_MUTANT_WORKERS", "6").strip()
    try:
        workers = max(1, int(workers_raw))
    except ValueError:
        workers = 6
    workers = min(workers, len(mutants))
    with ThreadPoolExecutor(max_workers=workers) as executor:
        outcomes = list(executor.map(evaluate_one, mutants))
    killed = sum(item[0] for item in outcomes)
    survived = sum(item[1] for item in outcomes)
    broken = sum(item[2] for item in outcomes)
    timed_out = sum(item[3] for item in outcomes)
    problematic = broken + timed_out
    denom = killed + survived
    return {"mutation_score": 100.0 * killed / denom if denom else None,
            "killed": killed, "survived": survived, "broken": broken,
            "timeout": timed_out, "problematic": problematic,
            "n_mutants": denom + problematic, **metadata}


